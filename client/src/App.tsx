import { useCallback, useEffect, useRef, useState } from 'react';
import type { GameView, Seat } from '@hidden-trump/shared';
import {
  connect,
  forgetRoom,
  rememberIdentity,
  rememberedName,
  rememberedRoom,
  request,
  sessionToken,
  type GameSocket,
} from './socket.js';
import { Landing } from './components/Landing.js';
import { Lobby } from './components/Lobby.js';
import { BiddingPanel } from './components/BiddingPanel.js';
import { TrumpPanel } from './components/TrumpPanel.js';
import { Table } from './components/Table.js';
import { RoundEnd } from './components/RoundEnd.js';
import { Scoreboard } from './components/Scoreboard.js';
import { Log } from './components/Log.js';

export interface JoinInfo {
  name: string;
  roomCode: string;
}

export function App() {
  const socketRef = useRef<GameSocket | null>(null);
  const [view, setView] = useState<GameView | null>(null);
  const [joinInfo, setJoinInfo] = useState<JoinInfo | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [connected, setConnected] = useState(false);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const socket = connect();
    socketRef.current = socket;

    socket.on('state', (next) => {
      setView(next);
      // Persist what the server actually resolved rather than what was typed:
      // the room code is usually generated by the server, and a reconnect
      // needs it before any view arrives.
      if (next.you) rememberIdentity(next.you.name, next.roomCode);
    });
    socket.on('error', ({ message }) => setError(message));
    socket.on('connect', () => {
      setConnected(true);
      // The server binds a session to the socket, so a refresh or a dropped
      // connection leaves us seatless. Re-join and the token wins our seat back.
      const name = rememberedName();
      if (!name || !rememberedRoom()) return;
      request<{ seat: Seat }>(socket, 'join_room', {
        name,
        roomCode: rememberedRoom(),
        token: sessionToken(),
      })
        .then(() => setJoinInfo({ name, roomCode: rememberedRoom() }))
        .catch((caught) => setError(caught instanceof Error ? caught.message : 'Could not rejoin that room.'));
    });
    socket.on('disconnect', () => setConnected(false));
    return () => {
      socket.removeAllListeners();
      socket.disconnect();
    };
  }, []);

  /** Run a server call, surfacing the error instead of throwing it away. */
  const act = useCallback(async (event: string, payload: unknown = {}) => {
    const socket = socketRef.current;
    if (!socket) return;
    setBusy(true);
    setError(null);
    try {
      await request(socket, event, payload);
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Something went wrong.');
    } finally {
      setBusy(false);
    }
  }, []);

  const join = useCallback(
    async (info: JoinInfo) => {
      const socket = socketRef.current;
      if (!socket) return;
      setBusy(true);
      setError(null);
      try {
        await request(socket, 'join_room', { ...info, token: sessionToken() });
        setJoinInfo(info);
      } catch (caught) {
        setError(caught instanceof Error ? caught.message : 'Could not join that room.');
      } finally {
        setBusy(false);
      }
    },
    [],
  );

  /** Escape hatch: without it, auto-rejoin makes a room impossible to leave. */
  const leave = useCallback(async () => {
    const socket = socketRef.current;
    if (!socket) return;
    setBusy(true);
    try {
      await request(socket, 'leave_room', {});
      forgetRoom();
      setView(null);
      setJoinInfo(null);
      setError(null);
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Could not leave the room.');
    } finally { setBusy(false); }
  }, []);

  const mySeat: Seat | null = view?.you?.seat ?? null;
  const roomCode = view?.roomCode ?? joinInfo?.roomCode ?? '';

  return (
    <div className="app">
      <header className="topbar">
        <h1>Hidden Trump</h1>
        <div className="topbar-right">
          {roomCode ? <span className="code" title="Share this code">{roomCode}</span> : null}
          <span className={connected ? 'dot ok' : 'dot bad'} title={connected ? 'Connected' : 'Disconnected'} />
          {joinInfo ? (
            <button type="button" className="leave" onClick={leave} title="Leave this table and pick another room">
              Leave
            </button>
          ) : null}
        </div>
      </header>

      {error ? (
        <button type="button" className="banner error" onClick={() => setError(null)}>
          {error} &times;
        </button>
      ) : null}

      {!view ? (
        <Landing onJoin={join} busy={busy} />
      ) : view.phase === 'lobby' ? (
        <Lobby view={view} onAct={act} busy={busy} />
      ) : (
        <main className="play">
          <Scoreboard view={view} />
          {view.phase === 'bidding' ? <BiddingPanel view={view} onAct={act} busy={busy} /> : null}
          {view.phase === 'trumpSelection' ? <TrumpPanel view={view} onAct={act} busy={busy} /> : null}
          {view.phase === 'playing' || view.phase === 'roundEnd' ? <Table view={view} onAct={act} busy={busy} /> : null}
          {view.phase === 'roundEnd' ? <RoundEnd view={view} onAct={act} busy={busy} /> : null}
          {mySeat !== null ? <Log view={view} /> : null}
        </main>
      )}
    </div>
  );
}
